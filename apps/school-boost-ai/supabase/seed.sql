-- 8. 出席記録（直近2週間分）
-- =========================================
-- 月曜スケジュールIDを取得して入れるため、サブクエリで対応

-- 幼児クラス・月曜スケジュールの出席
insert into public.attendance_records (schedule_id, member_id, lesson_date, status)
select
  s.id,
  m.id,
  (current_date - ((extract(dow from current_date)::int + 6) % 7)::int)::date, -- 直近月曜
  case when m.id = '20000000-0000-0000-0000-000000000001' then 'present'
       else 'absent' end
from public.schedules s
join public.classes c on c.id = s.class_id
join public.members m on m.id in (
  '20000000-0000-0000-0000-000000000001',
  '20000000-0000-0000-0000-000000000002'
)
where c.id = '10000000-0000-0000-0000-000000000001'
  and s.day_of_week = 1
on conflict do nothing;

